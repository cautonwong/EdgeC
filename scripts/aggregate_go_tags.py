#!/usr/bin/env python3
import os
import glob
import re

def aggregate_go_tags():
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    generated_files = sorted(glob.glob(os.path.join(project_root, "build", "products", "*", "generated", "tags.go")))
    
    if not generated_files:
        print("[Aggregate Go Tags] No generated tags.go files found under build/products/")
        return

    root_constants = {}  # name -> id
    root_metadata = {}   # id -> (name, data_type, unit)

    const_pattern = re.compile(r'^\s*([A-Z0-9_]+)\s*=\s*(\d+)')
    meta_pattern = re.compile(r'^\s*(\d+):\s*\{ID:\s*(\d+),\s*Name:\s*"([^"]+)",\s*DataType:\s*"([^"]+)",\s*Unit:\s*"([^"]*)"\}')

    for fpath in generated_files:
        parts = fpath.split(os.sep)
        try:
            prod_idx = parts.index("products") + 1
            prod_name = parts[prod_idx]
        except (ValueError, IndexError):
            prod_name = "default"

        pkg_name = prod_name.replace("-", "_").lower()
        prod_out_dir = os.path.join(project_root, "go", "pkg", "tags", pkg_name)
        os.makedirs(prod_out_dir, exist_ok=True)
        prod_out_file = os.path.join(prod_out_dir, "tags.go")

        with open(fpath, "r", encoding="utf-8") as f:
            lines = f.readlines()

        new_lines = []
        new_lines.append("// AUTO-GENERATED BY AGGREGATE GO TAGS (PRODUCT ISOLATED)\n")
        new_lines.append(f"package {pkg_name}\n\n")

        for line in lines:
            if line.startswith("package "):
                continue
            if "AUTO-GENERATED BY EDGEOS COMPILER" in line or "DO NOT EDIT MANUALLY" in line:
                continue
            new_lines.append(line)

            c_match = const_pattern.match(line)
            if c_match:
                name, tag_id = c_match.group(1), int(c_match.group(2))
                root_constants[name] = tag_id
                continue
            m_match = meta_pattern.match(line)
            if m_match:
                tag_id = int(m_match.group(1))
                name = m_match.group(3)
                dtype = m_match.group(4)
                unit = m_match.group(5)
                root_metadata[tag_id] = (name, dtype, unit)

        prod_content = "".join(new_lines)
        with open(prod_out_file, "w", encoding="utf-8") as f:
            f.write(prod_content)
        print(f"[Aggregate Go Tags] Generated product-isolated package: {prod_out_file}")

    # Generate root aggregated go/pkg/tags/tags.go
    out_dir = os.path.join(project_root, "go", "pkg", "tags")
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "tags.go")

    lines = []
    lines.append("// AUTO-GENERATED BY AGGREGATE GO TAGS\n")
    lines.append("// DO NOT EDIT MANUALLY\n")
    lines.append("package tags\n\n")
    lines.append("const (\n")
    for name, tag_id in sorted(root_constants.items(), key=lambda x: (x[1], x[0])):
        lines.append(f"\t{name} = {tag_id}\n")
    lines.append(")\n\n")
    lines.append("type TagMetadata struct {\n")
    lines.append("\tID       uint32\n")
    lines.append("\tName     string\n")
    lines.append("\tDataType string\n")
    lines.append("\tUnit     string\n")
    lines.append("}\n\n")
    lines.append("var Metadata = map[uint32]TagMetadata{\n")
    for tag_id in sorted(root_metadata.keys()):
        name, dtype, unit = root_metadata[tag_id]
        lines.append(f'\t{tag_id}: {{ID: {tag_id}, Name: "{name}", DataType: "{dtype}", Unit: "{unit}"}},\n')
    lines.append("}\n")

    content = "".join(lines)
    with open(out_file, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[Aggregate Go Tags] Updated {out_file} with {len(root_metadata)} tags from {len(generated_files)} products.")

if __name__ == "__main__":
    aggregate_go_tags()
