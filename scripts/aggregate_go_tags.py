#!/usr/bin/env python3
import os
import glob
import re

def aggregate_go_tags():
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    generated_files = glob.glob(os.path.join(project_root, "build", "products", "*", "generated", "tags.go"))
    
    # If build directory hasn't generated tags.go files yet, look in tmp or run compiler
    if not generated_files:
        print("[Aggregate Go Tags] No generated tags.go files found under build/products/")
        return

    constants = {}  # name -> id
    metadata = {}   # id -> (name, data_type, unit)

    const_pattern = re.compile(r'^\s*([A-Z0-9_]+)\s*=\s*(\d+)')
    meta_pattern = re.compile(r'^\s*(\d+):\s*\{ID:\s*(\d+),\s*Name:\s*"([^"]+)",\s*DataType:\s*"([^"]+)",\s*Unit:\s*"([^"]*)"\}')

    for fpath in generated_files:
        with open(fpath, "r", encoding="utf-8") as f:
            for line in f:
                c_match = const_pattern.match(line)
                if c_match:
                    name, tag_id = c_match.group(1), int(c_match.group(2))
                    constants[name] = tag_id
                    continue
                m_match = meta_pattern.match(line)
                if m_match:
                    tag_id = int(m_match.group(1))
                    name = m_match.group(3)
                    dtype = m_match.group(4)
                    unit = m_match.group(5)
                    metadata[tag_id] = (name, dtype, unit)

    out_dir = os.path.join(project_root, "go", "pkg", "tags")
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "tags.go")

    lines = []
    lines.append("// AUTO-GENERATED BY AGGREGATE GO TAGS")
    lines.append("// DO NOT EDIT MANUALLY")
    lines.append("package tags")
    lines.append("")
    lines.append("const (")
    # Sort constants by ID then Name
    for name, tag_id in sorted(constants.items(), key=lambda x: (x[1], x[0])):
        lines.append(f"\t{name} = {tag_id}")
    lines.append(")")
    lines.append("")
    lines.append("type TagMetadata struct {")
    lines.append("\tID       uint32")
    lines.append("\tName     string")
    lines.append("\tDataType string")
    lines.append("\tUnit     string")
    lines.append("}")
    lines.append("")
    lines.append("var Metadata = map[uint32]TagMetadata{")
    for tag_id in sorted(metadata.keys()):
        name, dtype, unit = metadata[tag_id]
        lines.append(f'\t{tag_id}: {{ID: {tag_id}, Name: "{name}", DataType: "{dtype}", Unit: "{unit}"}},')
    lines.append("}")
    lines.append("")

    content = "\n".join(lines)
    
    # Write only if changed
    if os.path.exists(out_file):
        with open(out_file, "r", encoding="utf-8") as f:
            old_content = f.read()
        if old_content == content:
            print(f"[Aggregate Go Tags] {out_file} is up to date ({len(metadata)} tags).")
            return

    with open(out_file, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[Aggregate Go Tags] Updated {out_file} with {len(metadata)} tags from {len(generated_files)} products.")

if __name__ == "__main__":
    aggregate_go_tags()
