package exporter

import (
	"contract-compiler/model"
	"contract-compiler/protocols"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

type DocExporter struct{}

type DocCtx struct {
	Product string
	Tags    []TagDoc
	Params  []model.ParamDef
}

type TagDoc struct {
	ID      uint32
	Name    string
	Unit    string
	Type    string
	RW      string
	Desc    string
	Binding string
}

func (e *DocExporter) Export(contract *model.EffectiveContract, resolved map[string][]protocols.ResolvedBinding, outDir string) error {
	ctx := DocCtx{
		Product: contract.Product,
		Params:  contract.Params,
	}

	// 建立 TagID 到 Binding 描述的映射
	bindingMap := make(map[uint32][]string)
	for proto, rbs := range resolved {
		for _, rb := range rbs {
			var detail string
			switch proto {
			case "MODBUS":
				detail = fmt.Sprintf("Modbus:0x%04X(scale:%.3f)", rb.Addr, rb.Scale)
			case "DLT645":
				detail = fmt.Sprintf("DLT645:%s", rb.DI)
			case "DLMS":
				detail = fmt.Sprintf("DLMS:%s", rb.OBIS)
			case "IEC104":
				detail = fmt.Sprintf("IEC104:%d", rb.IOA)
			default:
				detail = proto
			}
			bindingMap[rb.TagID] = append(bindingMap[rb.TagID], detail)
		}
	}

	for _, t := range contract.ActiveTags {
		rw := "R"
		if acc, ok := t.Attributes["access"]; ok {
			if strings.Contains(fmt.Sprintf("%v", acc), "W") {
				rw = "RW"
			}
		}

		ctx.Tags = append(ctx.Tags, TagDoc{
			ID:      t.ID,
			Name:    t.Name,
			Unit:    t.Unit,
			Type:    t.Type,
			RW:      rw,
			Desc:    t.Desc,
			Binding: strings.Join(bindingMap[t.ID], " | "),
		})
	}

	tmpl := `
# {{ .Product }} 通信协议规格书

## 1. 遥感/遥测数据表
| ID | 名称 | 单位 | 类型 | 读写 | 物理映射 | 描述 |
|----|------|------|------|------|----------|------|
{{- range .Tags }}
| {{.ID}} | {{.Name}} | {{.Unit}} | {{.Type}} | {{.RW}} | {{.Binding}} | {{.Desc}} |
{{- end }}

## 2. 系统参数 (Runtime Config)
| 参数名 | 类型 | 默认值 | 单位 | 范围 | 描述 |
|--------|------|--------|------|------|------|
{{- range .Params }}
| {{.Name}} | {{.Type}} | {{.Default}} | {{.Unit}} | [{{.Min}}, {{.Max}}] | {{.Desc}} |
{{- end }}

---
*Generated by EdgeOS Contract Compiler Exporter*
`

	t, err := template.New("doc").Parse(tmpl)
	if err != nil {
		return err
	}

	f, err := os.Create(filepath.Join(outDir, "manual.md"))
	if err != nil {
		return err
	}
	defer f.Close()

	return t.Execute(f, ctx)
}
