#!/usr/bin/env python3
"""Generate the SDK function tables from sdk/abi/functions.json.

The spec is the single list of Host ABI functions. The generated tables give
every language SDK the same function names, wasm symbols and status; a
`--check` run fails when a checked-in table is stale or the spec disagrees
with the WIT or sdk/abi_status.json.
"""

import argparse
import json
import os
import re
import sys

SPEC = "sdk/abi/functions.json"
WIT = "sdk/wit/app.v1.wit"
LEDGER = "sdk/abi_status.json"
OUTPUTS = {
    "sdk/c/generated/edge_app_abi_functions.h": "c",
    "sdk/python/edge_app_abi.py": "python",
    "sdk/go/edge_app_abi.go": "go",
    "sdk/js/edge_app_abi.mjs": "js",
}
WIT_FN = re.compile(r"^\s*([a-z][a-z0-9-]*):\s*func\(", re.MULTILINE)


def read(root, rel):
    with open(os.path.join(root, rel), "r", encoding="utf-8") as handle:
        return handle.read()


def macro(name):
    return name.upper()


def go_name(name):
    return "".join(part.capitalize() for part in name.split("_"))


def wit_functions(root):
    text = read(root, WIT)
    start = text.index("{", text.index("interface host"))
    depth = 0
    end = None
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                end = index
                break
    if end is None:
        raise ValueError("unterminated WIT host interface")
    return {match.group(1) for match in WIT_FN.finditer(text[start:end])}


def load_spec(root):
    spec = json.loads(read(root, SPEC))
    functions = spec.get("functions")
    if not isinstance(functions, list) or not functions:
        raise ValueError("sdk/abi/functions.json needs a non-empty functions list")
    seen = set()
    for fn in functions:
        for field in ("name", "wit", "status"):
            if not isinstance(fn.get(field), str) or not fn[field]:
                raise ValueError(f"function entry missing {field}: {fn!r}")
        if fn["name"] in seen:
            raise ValueError(f"duplicate function name {fn['name']}")
        seen.add(fn["name"])
        if fn["status"] not in ("implemented", "not_supported"):
            raise ValueError(f"bad status {fn['status']} for {fn['name']}")
        if fn["status"] == "implemented" and not fn.get("wasm_symbol"):
            raise ValueError(f"implemented function {fn['name']} needs a wasm_symbol")
    return spec


def validate(root, spec):
    functions = spec["functions"]
    spec_wit = {fn["wit"] for fn in functions}
    wit = wit_functions(root)
    if spec_wit != wit:
        missing = sorted(wit - spec_wit)
        extra = sorted(spec_wit - wit)
        raise ValueError(f"spec/WIT mismatch; missing={missing} extra={extra}")

    ledger = json.loads(read(root, LEDGER)).get("functions", {})
    if set(ledger) != spec_wit:
        raise ValueError(
            f"spec/ledger mismatch; missing={sorted(set(ledger) - spec_wit)} "
            f"extra={sorted(spec_wit - set(ledger))}"
        )
    for fn in functions:
        status = ledger[fn["wit"]].get("host")
        if status != fn["status"]:
            raise ValueError(f"{fn['wit']}: spec status {fn['status']} != ledger {status}")


def render_c(spec):
    lines = [
        "/* Generated by tools/gen_sdk.py from sdk/abi/functions.json. Do not edit. */",
        "#ifndef EDGE_APP_ABI_FUNCTIONS_H",
        "#define EDGE_APP_ABI_FUNCTIONS_H",
        "",
        "#include <stdbool.h>",
        "#include <stddef.h>",
        "",
        f'#define EDGE_APP_ABI_VERSION "{spec["abi_version"]}"',
        "",
    ]
    for fn in spec["functions"]:
        lines.append(f'#define EDGE_APP_FN_{macro(fn["name"])} "{fn["name"]}"')
        symbol = fn.get("wasm_symbol")
        value = f'"{symbol}"' if symbol else "NULL"
        lines.append(f"#define EDGE_APP_WASM_{macro(fn['name'])} {value}")
    lines += [
        "",
        "typedef struct {",
        "    const char *fn;",
        "    const char *wit;",
        "    const char *wasm_symbol;",
        "    bool implemented;",
        "} edge_app_abi_function_t;",
        "",
        "static const edge_app_abi_function_t edge_app_abi_functions[] = {",
    ]
    for fn in spec["functions"]:
        symbol = fn.get("wasm_symbol")
        symbol_value = f'"{symbol}"' if symbol else "NULL"
        implemented = "true" if fn["status"] == "implemented" else "false"
        lines.append(
            f'    {{"{fn["name"]}", "{fn["wit"]}", {symbol_value}, {implemented}}},'
        )
    lines += [
        "};",
        "",
        "#define EDGE_APP_ABI_FUNCTION_COUNT "
        f"{len(spec['functions'])}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def render_python(spec):
    lines = [
        '"""Generated by tools/gen_sdk.py from sdk/abi/functions.json. Do not edit."""',
        "",
        f'ABI_VERSION = "{spec["abi_version"]}"',
        "",
    ]
    for fn in spec["functions"]:
        lines.append(f'FN_{macro(fn["name"])} = "{fn["name"]}"')
        symbol = fn.get("wasm_symbol")
        lines.append(f"WASM_{macro(fn['name'])} = {repr(symbol)}")
    lines += ["", "ABI_FUNCTIONS = ["]
    for fn in spec["functions"]:
        lines.append(
            "    {\"name\": %r, \"wit\": %r, \"wasm_symbol\": %r, \"implemented\": %r},"
            % (fn["name"], fn["wit"], fn.get("wasm_symbol"), fn["status"] == "implemented")
        )
    lines += ["]", ""]
    return "\n".join(lines)


def render_go(spec):
    lines = [
        "// Code generated by tools/gen_sdk.py from sdk/abi/functions.json. DO NOT EDIT.",
        "",
        "package edgeappsdk",
        "",
        f'const ABIVersion = "{spec["abi_version"]}"',
        "",
    ]
    for fn in spec["functions"]:
        lines.append(f'const Fn{go_name(fn["name"])} = "{fn["name"]}"')
        symbol = fn.get("wasm_symbol") or ""
        lines.append(f'const Wasm{go_name(fn["name"])} = "{symbol}"')
    lines += [
        "",
        "type ABIFunction struct {",
        "\tName       string",
        "\tWIT        string",
        "\tWasmSymbol string",
        "\tImplemented bool",
        "}",
        "",
        "var ABIFunctions = []ABIFunction{",
    ]
    for fn in spec["functions"]:
        symbol = fn.get("wasm_symbol") or ""
        implemented = "true" if fn["status"] == "implemented" else "false"
        lines.append(
            f'\t{{"{fn["name"]}", "{fn["wit"]}", "{symbol}", {implemented}}},'
        )
    lines += ["}", ""]
    return "\n".join(lines)


def render_js(spec):
    lines = [
        "// Generated by tools/gen_sdk.py from sdk/abi/functions.json. Do not edit.",
        "",
        f'export const ABI_VERSION = "{spec["abi_version"]}";',
        "",
    ]
    for fn in spec["functions"]:
        lines.append(f'export const FN_{macro(fn["name"])} = "{fn["name"]}";')
        symbol = fn.get("wasm_symbol")
        lines.append(f"export const WASM_{macro(fn['name'])} = {json.dumps(symbol)};")
    lines += ["", "export const ABI_FUNCTIONS = ["]
    for fn in spec["functions"]:
        lines.append(
            "  { name: %s, wit: %s, wasmSymbol: %s, implemented: %s },"
            % (
                json.dumps(fn["name"]),
                json.dumps(fn["wit"]),
                json.dumps(fn.get("wasm_symbol")),
                "true" if fn["status"] == "implemented" else "false",
            )
        )
    lines += ["];", ""]
    return "\n".join(lines)


RENDERERS = {"c": render_c, "python": render_python, "go": render_go, "js": render_js}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=os.path.abspath(os.path.join(__file__, "..", "..")))
    parser.add_argument("--check", action="store_true", help="fail when outputs are stale")
    args = parser.parse_args()
    root = os.path.abspath(args.root)

    try:
        spec = load_spec(root)
        validate(root, spec)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"gen_sdk: {exc}")
        return 1

    stale = []
    for rel, kind in OUTPUTS.items():
        content = RENDERERS[kind](spec)
        path = os.path.join(root, rel)
        current = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        if current != content:
            stale.append(rel)
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(content)

    if args.check:
        if stale:
            print("gen_sdk: stale generated files:")
            for rel in stale:
                print(f"  {rel}")
            return 1
        print(f"gen_sdk: ok ({len(spec['functions'])} functions)")
        return 0

    for rel in stale:
        print(f"gen_sdk: wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
