#!/usr/bin/env python3
import yaml
import sys
from pathlib import Path

def main():
    if len(sys.argv) != 3:
        print("Usage: python contract_compiler.py <product_contract.yaml> <output_dir>")
        sys.exit(1)

    product_contract_path = Path(sys.argv[1])
    output_dir = Path(sys.argv[2])

    # Create output directories
    output_include_dir = output_dir / "include"
    output_src_dir = output_dir / "src"
    output_include_dir.mkdir(parents=True, exist_ok=True)
    output_src_dir.mkdir(parents=True, exist_ok=True)

    # --- 1. Load and Resolve Contracts ---
    print(f"Compiler: Loading product contract from {product_contract_path}")
    with open(product_contract_path, 'r') as f:
        product_contract = yaml.safe_load(f)
    
    enabled_tag_names = set(product_contract.get('enabled_tags', []))

    project_root = Path(__file__).parent.parent
    global_tags_path = project_root / "contracts/schema/tags.yaml"
    
    print(f"Compiler: Loading global tags from {global_tags_path}")
    with open(global_tags_path, 'r') as f:
        global_tags = yaml.safe_load(f)

    effective_tags = [tag for tag in global_tags.get('tags', []) if tag['name'] in enabled_tag_names]

    # --- 2. Generate edge_tag_id.h ---
    tag_id_enums = "\n".join([f"    TAG_{tag['name']} = {tag['id']}," for tag in effective_tags])
    tag_id_h_content = f"""#pragma once

// Auto-generated by contract_compiler.py. DO NOT EDIT.

typedef enum {{
    TAG_INVALID = 0,
{tag_id_enums}
}} edge_tag_id_t;
"""
    with open(output_include_dir / "edge_tag_id.h", 'w') as f:
        f.write(tag_id_h_content)
    print(f"Compiler: Generated {output_include_dir / 'edge_tag_id.h'}")

    # --- 3. Generate edge_tag_config.h ---
    config_macros = []
    all_tag_names = {tag['name'] for tag in global_tags.get('tags', [])}
    for name in sorted(list(all_tag_names)):
        is_enabled = 1 if name in enabled_tag_names else 0
        config_macros.append(f"#define IS_ENABLED_TAG_{name} {is_enabled}")

    config_h_content = f"""#pragma once

// Auto-generated by contract_compiler.py. DO NOT EDIT.

{"\n".join(config_macros)}

#define IS_ENABLED(tag) IS_ENABLED_##tag
"""
    with open(output_include_dir / "edge_tag_config.h", 'w') as f:
        f.write(config_h_content)
    print(f"Compiler: Generated {output_include_dir / 'edge_tag_config.h'}")

    # --- 4. Generate edge_meta.h and tag_meta.c ---
    meta_h_template = """#pragma once

// Auto-generated by contract_compiler.py. DO NOT EDIT.

#include "edge_tag_id.h"

typedef struct {
    edge_tag_id_t id;
    const char* name;
    const char* unit;
    const char* desc;
} edge_tag_meta_t;

const edge_tag_meta_t* edge_get_meta(edge_tag_id_t tag);
"""
    with open(output_include_dir / "edge_meta.h", 'w') as f:
        f.write(meta_h_template)
    print(f"Compiler: Generated {output_include_dir / 'edge_meta.h'}")

    # Generate the C source file
    meta_structs = []
    for tag in effective_tags:
        # Ensure description is properly escaped C-string
        desc = tag.get("desc", "").replace('"', '\\"')
        meta_structs.append(
            f'    [{tag["id"]}] = {{ .id=TAG_{tag["name"]}, .name="{tag["name"]}", .unit="{tag["unit"]}", .desc="{desc}" }},'
        )
    
    max_id = max(tag['id'] for tag in global_tags.get('tags', [])) if global_tags.get('tags') else 0

    meta_c_content = f"""#include "edge_meta.h"
#include <stddef.h>

// Auto-generated by contract_compiler.py. DO NOT EDIT.

static const edge_tag_meta_t g_tag_meta_table[{max_id} + 1] = {{
{"\n".join(meta_structs)}
}};

const edge_tag_meta_t* edge_get_meta(edge_tag_id_t tag) {{
    if (tag > 0 && tag <= {max_id} && g_tag_meta_table[tag].name != NULL) {{
        return &g_tag_meta_table[tag];
    }}
    return NULL;
}}
"""
    with open(output_src_dir / "tag_meta.c", 'w') as f:
        f.write(meta_c_content)
    print(f"Compiler: Generated {output_src_dir / 'tag_meta.c'}")

if __name__ == "__main__":
    main()
