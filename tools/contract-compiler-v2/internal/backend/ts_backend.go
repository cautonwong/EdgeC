package backend

import (
	"contract-compiler-v2/internal/ir"
	"fmt"
	"os"
	"path/filepath"
)

type TsBackend struct {
	OutDir string
}

func (b *TsBackend) Emit(contract *ir.ContractIR) error {
	if err := b.emitTs(contract); err != nil { return err }
	if err := b.emitSql(contract); err != nil { return err }
	return nil
}

func (b *TsBackend) emitTs(contract *ir.ContractIR) error {
	f, err := os.Create(filepath.Join(b.OutDir, "tags_type.ts"))
	if err != nil { return err }
	defer f.Close()

	fmt.Fprintln(f, "/** AUTO-GENERATED BY EDGEOS COMPILER V5 (IR-BASED) */")
	fmt.Fprintln(f, "export enum TagID {")
	for _, t := range contract.Tags {
		fmt.Fprintf(f, "  %s = %d,\n", t.Name, t.ID)
	}
	fmt.Fprintln(f, "}")
	
	fmt.Fprintln(f, "export interface TagMetadata { id: number; name: string; type: string; unit?: string; }")
	fmt.Fprintln(f, "export const TAG_METADATA: Record<TagID, TagMetadata> = {")
	for _, t := range contract.Tags {
		fmt.Fprintf(f, "  [TagID.%s]: { id: %d, name: \"%s\", type: \"%s\", unit: \"%s\" },\n",
			t.Name, t.ID, t.Name, t.DataType, t.Unit)
	}
	fmt.Fprintln(f, "};")
	return nil
}

func (b *TsBackend) emitSql(contract *ir.ContractIR) error {
	f, err := os.Create(filepath.Join(b.OutDir, "init.sql"))
	if err != nil { return err }
	defer f.Close()
	fmt.Fprintln(f, "-- Empty placeholder for regression")
	return nil
}
