package backend

import (
	"contract-compiler-v2/internal/ir"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type GoBackend struct {
	OutDir string
}

func (b *GoBackend) Emit(contract *ir.ContractIR) error {
	if err := b.emitTags(contract); err != nil { return err }
	return nil
}

func (b *GoBackend) emitTags(contract *ir.ContractIR) error {
	// Let's create a directory for Go bindings if we want, or just write to OutDir.
	// Since we are writing to the generated folder which is typically build/products/iems/generated,
	// maybe we can write a single Go file with package name "tags".
	f, err := os.Create(filepath.Join(b.OutDir, "tags.go"))
	if err != nil { return err }
	defer f.Close()

	fmt.Fprintln(f, "// AUTO-GENERATED BY EDGEOS COMPILER V2")
	fmt.Fprintln(f, "// DO NOT EDIT MANUALLY")
	fmt.Fprintln(f, "package tags")
	fmt.Fprintln(f, "")
	
	// Create constants for each Tag ID
	fmt.Fprintln(f, "const (")
	for _, t := range contract.Tags {
		fmt.Fprintf(f, "\t%s = %d\n", strings.ToUpper(t.Name), t.ID)
	}
	fmt.Fprintln(f, ")")
	fmt.Fprintln(f, "")

	// Create a metadata map
	fmt.Fprintln(f, "type TagMetadata struct {")
	fmt.Fprintln(f, "\tID       uint32")
	fmt.Fprintln(f, "\tName     string")
	fmt.Fprintln(f, "\tDataType string")
	fmt.Fprintln(f, "\tUnit     string")
	fmt.Fprintln(f, "}")
	fmt.Fprintln(f, "")

	fmt.Fprintln(f, "var Metadata = map[uint32]TagMetadata{")
	for _, t := range contract.Tags {
		fmt.Fprintf(f, "\t%d: {ID: %d, Name: \"%s\", DataType: \"%s\", Unit: \"%s\"},\n",
			t.ID, t.ID, t.Name, t.DataType, t.Unit)
	}
	fmt.Fprintln(f, "}")

	return nil
}
