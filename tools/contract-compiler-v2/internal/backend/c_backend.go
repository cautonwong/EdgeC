	fmt.Fprintln(f, "int edge_tag_get_compact_index(edge_tag_id_t tag_id);")
	fmt.Fprintln(f, "bool edge_router_needs_wakeup(int index);")
	fmt.Fprintln(f, "const char* edge_resolve_bus_path(int bus_id);")
