	defer f.Close()

	fmt.Fprintln(f, "/* AUTO-GENERATED BY EDGEOS COMPILER V5 (SEMANTIC-BASED) */")
	fmt.Fprintln(f, "#ifndef EDGE_CONTRACTS_H")
	fmt.Fprintln(f, "#define EDGE_CONTRACTS_H")
	fmt.Fprintln(f, "")
	fmt.Fprintln(f, "#include <stdint.h>")
