	fmt.Fprintln(f, "extern const edge_tag_meta_t g_tag_metadata[];")
	fmt.Fprintln(f, "extern const uint32_t g_tag_metadata_len;")
	fmt.Fprintln(f, "extern const edge_connectivity_t g_connectivity_configs[];")
