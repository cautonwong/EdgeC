func newControlDB(t *testing.T, path string) {
	t.Helper()
	db, err := sql.Open("sqlite3", path)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	stmts := []string{
		"PRAGMA user_version = 5",
		`CREATE TABLE edge_settings (product TEXT, tag_id INTEGER, val BLOB, PRIMARY KEY (product, tag_id))`,
		`INSERT INTO edge_settings VALUES ('iems', 1, 'configured')`,
		`CREATE TABLE app_task (id TEXT PRIMARY KEY, kind INTEGER NOT NULL,
			idempotency_key TEXT NOT NULL UNIQUE, state INTEGER NOT NULL,
			created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL, result_json TEXT)`,
	}
	for _, stmt := range stmts {
		if _, err := db.Exec(stmt); err != nil {
			t.Fatalf("%s: %v", stmt, err)
		}
	}
}

func TestMaintenanceGuardRejectsWrites(t *testing.T) {
	maintenanceMode.Store(true)
	defer maintenanceMode.Store(false)

	reached := false
	handler := maintenanceGuard(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		reached = true
		w.WriteHeader(http.StatusOK)
	}))

	for _, method := range []string{http.MethodPost, http.MethodPut, http.MethodPatch, http.MethodDelete} {
		reached = false
		rec := httptest.NewRecorder()
		handler.ServeHTTP(rec, httptest.NewRequest(method, "/api/v1/actor/batch/set", strings.NewReader("{}")))
		if rec.Code != http.StatusLocked {
			t.Errorf("%s status = %d, want %d", method, rec.Code, http.StatusLocked)
		}
		if reached {
			t.Errorf("%s reached the handler in maintenance mode", method)
		}
	}

	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/health", nil))
	if rec.Code != http.StatusOK || !reached {
		t.Errorf("GET status = %d, reached = %v; reads must stay available", rec.Code, reached)
	}
}

func TestRestoreHandlerRejectsConcurrentRestore(t *testing.T) {
	maintenanceMode.Store(true)
	defer maintenanceMode.Store(false)

	rec := httptest.NewRecorder()
	handleRestore(rec, httptest.NewRequest(http.MethodPost, "/api/v1/system/restore",
		strings.NewReader(`{"backup_path":"/tmp/backup"}`)))
	if rec.Code != http.StatusLocked {
		t.Fatalf("status = %d, want %d", rec.Code, http.StatusLocked)
	}
}

func TestBackupAndRestoreHandlers(t *testing.T) {
	dir := t.TempDir()
	src := filepath.Join(dir, "iems.db")
	newControlDB(t, src)

	backupRoot := filepath.Join(dir, "backups")
	tokenPath := filepath.Join(dir, "session.token")
	if err := os.WriteFile(tokenPath, []byte("old-token\n"), 0600); err != nil {
		t.Fatal(err)
	}
	t.Setenv("EDGE_DB_PATH", src)
	t.Setenv("EDGE_BACKUP_DIR", backupRoot)
	t.Setenv("EDGE_PLATFORM_VERSION", "5.0.0")
	t.Setenv("EDGE_SESSION_TOKEN_FILE", tokenPath)

	rec := httptest.NewRecorder()
	handleBackup(rec, httptest.NewRequest(http.MethodPost, "/api/v1/system/backup", nil))
	if rec.Code != http.StatusOK {
		t.Fatalf("backup status = %d: %s", rec.Code, rec.Body.String())
	}
	var backupResponse struct {
		Data struct {
			BackupPath string `json:"backup_path"`
		} `json:"data"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &backupResponse); err != nil {
		t.Fatal(err)
	}
	if backupResponse.Data.BackupPath == "" {
		t.Fatal("backup response has no backup_path")
	}

	target := filepath.Join(dir, "restored-device", "iems.db")
	if err := os.MkdirAll(filepath.Dir(target), 0700); err != nil {
		t.Fatal(err)
	}
	t.Setenv("EDGE_DB_PATH", target)

	body, err := json.Marshal(map[string]string{"backup_path": backupResponse.Data.BackupPath})
	if err != nil {
		t.Fatal(err)
	}
	rec = httptest.NewRecorder()
	handleRestore(rec, httptest.NewRequest(http.MethodPost, "/api/v1/system/restore", strings.NewReader(string(body))))
	if rec.Code != http.StatusOK {
		t.Fatalf("restore status = %d: %s", rec.Code, rec.Body.String())
	}
	if maintenanceMode.Load() {
		t.Error("maintenance mode still set after a successful restore")
	}

	token, err := os.ReadFile(tokenPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.TrimSpace(string(token)) == "old-token" {
		t.Error("session token was not regenerated by restore")
	}

	// Restoring over an existing database must snapshot it first.
	rec = httptest.NewRecorder()
	handleRestore(rec, httptest.NewRequest(http.MethodPost, "/api/v1/system/restore", strings.NewReader(string(body))))
	if rec.Code != http.StatusOK {
		t.Fatalf("second restore status = %d: %s", rec.Code, rec.Body.String())
	}
	var secondRestore struct {
		Data struct {
			SafetyBackupDir string `json:"safety_backup_dir"`
		} `json:"data"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &secondRestore); err != nil {
		t.Fatal(err)
	}
	if secondRestore.Data.SafetyBackupDir == "" {
		t.Fatal("restore over an existing database reported no safety backup")
	}
	if _, err := os.Stat(filepath.Join(secondRestore.Data.SafetyBackupDir, "manifest.json")); err != nil {
		t.Errorf("safety backup manifest: %v", err)
	}

	db, err := sql.Open("sqlite3", target)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	var value string
	if err := db.QueryRow(`SELECT val FROM edge_settings WHERE product='iems'`).Scan(&value); err != nil {
		t.Fatalf("restored row: %v", err)
	}
	if value != "configured" {
		t.Errorf("restored value = %q", value)
	}
}
